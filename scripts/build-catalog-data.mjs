#!/usr/bin/env node
/**
 * Generates the catalogue modules from the JSON under content/.
 *
 *   node scripts/build-catalog-data.mjs
 *
 * content/catalog.en.json is the single source of the published starting
 * prices and of the English copy; it becomes
 * supabase/functions/_shared/catalog.data.ts, which the browser and the Edge
 * Functions both import, so both runtimes read exactly the same values.
 *
 * content/catalog.{ru,uz,zh}.json carry the same structure in the other guest
 * languages and become lib/i18n/catalog-translations.ts, which only the
 * browser imports. Only their text is ever used: prices, ids and profiles
 * always come from the English file, and lib/i18n/catalog.test.ts fails if a
 * translation drifts from it.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectDir = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const contentDir = path.join(projectDir, 'content');
const translatedLocales = ['ru', 'uz', 'zh'];

function readCatalog(locale) {
  return JSON.parse(readFileSync(path.join(contentDir, `catalog.${locale}.json`), 'utf8'));
}

const data = readCatalog('en');
const dataPath = path.join(projectDir, 'supabase', 'functions', '_shared', 'catalog.data.ts');

writeFileSync(
  dataPath,
  `// Generated by scripts/build-catalog-data.mjs from content/catalog.en.json.
// Do not edit by hand: change the JSON and re-run the script.
// Guest-facing copy and published starting prices only; no purchase prices,
// partner payouts or commissions belong in this file.

export const catalogData = ${JSON.stringify(data, null, 2)} as const;
`,
  'utf8',
);

console.log(`catalog.data.ts written from content/catalog.en.json (${data.offers.length} offers, version ${data.version})`);

const translations = Object.fromEntries(translatedLocales.map((locale) => [locale, readCatalog(locale)]));
const translationsPath = path.join(projectDir, 'lib', 'i18n', 'catalog-translations.ts');

writeFileSync(
  translationsPath,
  `// Generated by scripts/build-catalog-data.mjs from content/catalog.{${translatedLocales.join(',')}}.json.
// Do not edit by hand: change the JSON and re-run the script.
// Guest-facing text in the other languages. Prices, ids and profiles are read
// from the English catalogue, never from here.

import type { CatalogSource } from '../../supabase/functions/_shared/catalog';

export const catalogTranslations: Record<${translatedLocales.map((locale) => `'${locale}'`).join(' | ')}, CatalogSource> = ${JSON.stringify(translations, null, 2)};
`,
  'utf8',
);

console.log(`catalog-translations.ts written for ${translatedLocales.join(', ')}`);
