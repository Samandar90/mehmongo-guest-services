#!/usr/bin/env node
/**
 * Generates supabase/functions/_shared/catalog.data.ts from content/catalog.en.json.
 *
 *   node scripts/build-catalog-data.mjs
 *
 * The JSON stays the single source of the guest-facing copy and published
 * prices; the generated module is what the browser and the Edge Functions
 * import, so both runtimes read exactly the same values. lib/catalog.test.ts
 * fails if the two ever drift apart.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectDir = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const sourcePath = path.join(projectDir, 'content', 'catalog.en.json');
const targetPath = path.join(projectDir, 'supabase', 'functions', '_shared', 'catalog.data.ts');

const source = readFileSync(sourcePath, 'utf8');
const data = JSON.parse(source);

const header = `// Generated by scripts/build-catalog-data.mjs from content/catalog.en.json.
// Do not edit by hand: change the JSON and re-run the script.
// Guest-facing copy and published starting prices only; no purchase prices,
// partner payouts or commissions belong in this file.

`;

writeFileSync(
  targetPath,
  `${header}export const catalogData = ${JSON.stringify(data, null, 2)} as const;\n`,
  'utf8',
);

console.log(`catalog.data.ts written from ${path.relative(projectDir, sourcePath)} (${data.offers.length} offers, version ${data.version})`);
